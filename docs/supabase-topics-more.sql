-- ============================================================
-- 「校园拾光」· 话题清单扩容（8 → 18）
-- ============================================================
--
-- 【这是什么】
--   把 posts_topics_allowed 这份 CHECK 名单从 8 个换成 18 个。
--   原来那 8 个全是「氛围」类（食堂、图书馆、晚霞、emo、求组队、学习、运动、
--   随手拍），缺**事务型**的场景 —— 同学想发条失物招领、二手、拼单，
--   在发布页挑不到合适的词，结果就是干脆不打标签：
--   线上 11 条过审分享里只有 1 条带了话题（9%）。
--   新增的 10 个：失物招领、二手闲置、拼单拼车、兼职信息、社团招新、
--                 选课考试、找室友、求助提问、通知吐槽、毕业季。
--
-- 【为什么不直接放开让同学自己造词】
--   话题是**公开**的：进地址栏、进广场筛选条、进卡片、还能被分享出去。
--   放开就等于开了一条绕过内容审核的公开文本通道，而且任意标签能把分散的
--   内容**聚到一起**（#高二3班 这种），这正是本站最不该出现的东西。
--   想让同学有参与感，走发布页的「告诉站主加一个」：
--   提案进反馈表（前缀【话题建议】），站主采纳了才加进这份名单。
--
-- 【为什么要跑】
--   页面已经先上了（app.js 里那份 TOPICS 是 18 个）。库里的 CHECK 还是旧的，
--   所以**在跑完之前**，同学如果挑了新增的那 10 个词：
--     · 内容照样发得出去 —— 前端拿到 23514（CHECK 不通过）会把话题摘掉重发，
--       不会因为一条标签弄丢整篇分享（见 app.js isMissingColumn 里那条分支）；
--     · 但那条分享不带话题，而且这一页会话里的话题会先关掉（刷新页面即恢复）。
--   跑完之后就正常了，**不需要重新发布页面**。
--
-- 【怎么跑】
--   Supabase 控制台 → 左侧 SQL Editor → New query → 整段粘进去 → Run。
--   整段重跑没关系（drop constraint if exists + add）。
--   嫌注释太长，用同目录的 supabase-topics-more-flat.sql（一条语句一行）。
--
-- 【跑完怎么验证】
--   在 SQL Editor 里执行：
--     select pg_get_constraintdef(oid) from pg_constraint
--      where conname = 'posts_topics_allowed';
--   array[...] 里应该能看到「失物招领」「二手闲置」这些新词。
--   （PostgREST 那边看不到 pg_constraint，所以线上探针 tools/topics_probe.py
--     验不了这一条，只能在这里看。）
--
-- 【只动这一条约束】
--   列、列级 grant、gin 索引、my_posts 视图都是上一份迁移
--   （supabase-topics.sql）建的，这里一概不碰 —— 也就没有「新列忘了
--   授权 → 42501」「视图少一列 → 42703」那两种坑。
--
-- 【回滚】
--   把下面 array[...] 换回原来那 8 个词重跑即可（换约束不动任何数据）：
--     array['食堂','图书馆','晚霞','emo','求组队','学习','运动','随手拍']::text[]
--
-- 【安全说明】
--   只把 CHECK 的名单换长：不新增读取通道、不碰 RLS、不碰任何人的数据。
--   名单仍然是固定的一份，不开放自由造词（理由见 docs/PLAN_phase2.md）。
-- ============================================================

alter table public.posts drop constraint if exists posts_topics_allowed;
alter table public.posts
  add constraint posts_topics_allowed check (
    cardinality(topics) <= 3
    and topics <@ array['食堂','图书馆','晚霞','emo','求组队','学习','运动','随手拍',
                       '失物招领','二手闲置','拼单拼车','兼职信息','社团招新',
                       '选课考试','找室友','求助提问','通知吐槽','毕业季']::text[]
  );

notify pgrst, 'reload schema';
